def branch(net, name):
    for table in ("line", "trafo"):
        hit = net[table].index[net[table].name == name]
        if len(hit):
            return table, hit[0]
    raise KeyError(name)


# A line shunt belongs to its branch, so it drops out whenever the branch opens
def set_status(net, name, closed):
    table, i = branch(net, name)
    net[table].at[i, "in_service"] = closed
    net.shunt.loc[net.shunt.name == f"LS{name}", "in_service"] = closed


def set_tap(net, name, tap):
    _, i = branch(net, name)
    f = int(net.trafo.at[i, "tap_from"])
    col = "vn_hv_kv" if net.trafo.at[i, "hv_bus"] == f else "vn_lv_kv"
    net.trafo.at[i, col] = net.bus.vn_kv[f] * tap
    net.trafo.at[i, "tap"] = tap


# Mvar limits with PowerWorld's back-off: a unit parked on a limit becomes a fixed-Q injection and returns
#    to voltage control once its bus voltage crosses the setpoint on the side the limit cannot explain.
#    LTC taps and switched shunts stay where they are (controls frozen).
def solve_pw(net, vtol=5e-5, max_outer=50, **kw):
    pv = net.gen.index[net.gen.pv_on.astype(bool)].tolist()
    parked = {}
    for _ in range(max_outer):
        net.sgen.drop(net.sgen.index, inplace=True)
        net.gen.loc[pv, "in_service"] = True
        for i, side in parked.items():
            net.gen.at[i, "in_service"] = False
            pp.create_sgen(net, net.gen.at[i, "bus"], p_mw=net.gen.at[i, "p_mw"],
                           q_mvar=net.gen.at[i, f"{side}_q_mvar"], name=f"park{i}")
        pp.runpp(net, enforce_q_lims=False, trafo_model="pi", **kw)
        vb = net.res_bus.vm_pu
        switch = None
        for i in pv:
            vset, b = net.gen.at[i, "vm_pu"], net.gen.at[i, "bus"]
            if i in parked:
                if (parked[i] == "max" and vb[b] > vset + vtol) or (parked[i] == "min" and vb[b] < vset - vtol):
                    switch = (i, None)
            elif net.res_gen.at[i, "q_mvar"] > net.gen.at[i, "max_q_mvar"] + 1e-6:
                switch = (i, "max")
            elif net.res_gen.at[i, "q_mvar"] < net.gen.at[i, "min_q_mvar"] - 1e-6:
                switch = (i, "min")
            if switch:
                break
        if switch is None:
            net["parked"] = dict(parked)
            return net
        i, side = switch
        if side is None:
            del parked[i]
        else:
            parked[i] = side
    raise RuntimeError("Mvar limit switching did not settle")


def gen_q(net):
    q = pd.Series(np.nan, index=net.gen.index)
    q[net.gen.in_service] = net.res_gen.q_mvar[net.gen.in_service]
    for i in net.parked:
        q[i] = net.res_sgen.q_mvar[net.sgen.name == f"park{i}"].iloc[0]
    return q


def losses(net):
    return net.res_line.pl_mw.sum() + net.res_trafo.pl_mw.sum()


# Branch current at a given end as percent of the MVA limit at nominal voltage (PowerWorld "Amp" limits)
def amp_at(net, name, end_bus):
    table, i = branch(net, name)
    if table == "line":
        end = "from" if net.line.at[i, "from_bus"] == end_bus else "to"
        amps = net.res_line.at[i, f"i_{end}_ka"] * 1e3
        lim = net.line.at[i, "max_i_ka"] * 1e3
    else:
        end = "hv" if net.trafo.at[i, "hv_bus"] == end_bus else "lv"
        amps = net.res_trafo.at[i, f"i_{end}_ka"] * 1e3
        lim = net.trafo.at[i, "lim_mva"] / (math.sqrt(3) * net.bus.vn_kv[end_bus]) * 1e3
    return amps, amps / lim * 100


